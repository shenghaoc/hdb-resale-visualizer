-- Benchmark-only PostgreSQL 18 schema. Never apply to Neon production.
-- Integer identity preserves source multiplicity; source facts are deliberately NOT unique.
CREATE TABLE transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month TEXT NOT NULL CHECK (month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  town TEXT NOT NULL, block TEXT NOT NULL, street_name TEXT NOT NULL,
  address_key TEXT NOT NULL, flat_type TEXT NOT NULL, storey_range TEXT NOT NULL,
  floor_area_sqm DOUBLE PRECISION NOT NULL,
  -- SQLite INTEGER affinity contains fractional source prices; double preserves current Number semantics.
  lease_commence_year SMALLINT, resale_price DOUBLE PRECISION NOT NULL, flat_model TEXT
);
-- Three actual comparable COUNT/filter/ORDER BY month DESC LIMIT 150 paths.
CREATE INDEX tx_block_flat_month ON transactions(town,block,flat_type,month DESC);
CREATE INDEX tx_street_flat_month ON transactions(street_name,flat_type,month DESC);
CREATE INDEX tx_town_flat_month ON transactions(town,flat_type,month DESC);
-- D1's standalone flat-type/month/lease/area indexes have no current independent runtime consumer.
-- Reconciliation seeks by identity PK. Do not add speculative indexes before measuring.
CREATE TABLE blocks (
  address_key TEXT PRIMARY KEY, town TEXT NOT NULL, block TEXT NOT NULL,
  street_name TEXT NOT NULL, display_name TEXT, lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL, median_price DOUBLE PRECISION NOT NULL,
  price_per_sqm_median DOUBLE PRECISION NOT NULL, transaction_count INTEGER NOT NULL,
  floor_area_min DOUBLE PRECISION NOT NULL, floor_area_max DOUBLE PRECISION NOT NULL,
  lease_commence_year SMALLINT NOT NULL, latest_month TEXT NOT NULL,
  available_min_month TEXT NOT NULL, available_max_month TEXT NOT NULL,
  flat_types_json JSONB NOT NULL, flat_models_json JSONB NOT NULL,
  median_price_by_flat_type_json JSONB, median_price_per_sqm_by_flat_type_json JSONB,
  nearest_mrt_json JSONB, nearby_mrts_json JSONB, postal_code TEXT,
  flat_type_cohorts_json JSONB
);
-- Town-scoped bulk/search and full ordered block summaries.
CREATE INDEX blocks_town ON blocks(town);
CREATE INDEX blocks_sort ON blocks(median_price DESC,transaction_count DESC);
-- Current suggestion dictionary uses address-key keyset reads; legacy prefix indexes omitted.
CREATE TABLE block_details (address_key TEXT PRIMARY KEY, json JSONB NOT NULL);
CREATE TABLE comparisons (address_key TEXT PRIMARY KEY, json JSONB NOT NULL);
CREATE TABLE town_flat_type_trends (
  town TEXT NOT NULL, flat_type TEXT NOT NULL, month TEXT NOT NULL,
  median_price DOUBLE PRECISION NOT NULL, median_price_per_sqm DOUBLE PRECISION NOT NULL,
  transaction_count INTEGER NOT NULL, PRIMARY KEY(town,flat_type,month)
);
CREATE TABLE manifest (id SMALLINT PRIMARY KEY CHECK(id=1), json JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL);
CREATE TABLE mrt_geojson (kind TEXT PRIMARY KEY CHECK(kind IN ('stations','exits')),json JSONB NOT NULL,updated_at TIMESTAMPTZ NOT NULL);
CREATE TABLE geocode_cache (
  cache_key TEXT PRIMARY KEY, lat DOUBLE PRECISION NOT NULL,lng DOUBLE PRECISION NOT NULL,
  postal_code TEXT,display_name TEXT,search_value TEXT NOT NULL,updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE walking_time_cache (
  cache_key TEXT PRIMARY KEY,walking_time_seconds INTEGER NOT NULL,
  walking_distance_meters INTEGER,updated_at TIMESTAMPTZ NOT NULL
);
-- Schema only; no private production shortlist contents are exported.
CREATE TABLE shortlists (code_hash TEXT PRIMARY KEY,items_json JSONB NOT NULL,updated_at TIMESTAMPTZ NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX shortlists_updated_at ON shortlists(updated_at);
